#!/usr/bin/env python3
"""Generates library/src/families/*.cpp and FamilyTables.h from the tag family sources of AprilRobotics apriltag.

usage: gen_families.py <apriltag source dir> [output dir]

The source directory is the fetched upstream tree (for example build/_deps/apriltag-src); the output defaults to
library/src/families beside this script's tools directory. The code values are upstream's, BSD-2-Clause: every
generated file carries upstream's copyright notice.
"""
import pathlib
import re
import sys

FAMILIES = ["tag36h11", "tag25h9", "tag16h5", "tagCircle21h7", "tagCircle49h12", "tagStandard41h12",
            "tagStandard52h13", "tagCustom48h12"]
UPSTREAM_TAG = "v3.4.5"


def const_name(name):
    return "k" + name[0].upper() + name[1:]


def parse(text, name):
    codes = [int(m.group(1), 16) for m in re.finditer(r"0x([0-9a-fA-F]+)UL", text.split("_create()")[0])]
    scalar = {}
    for key in ("h", "ncodes", "nbits", "width_at_border", "total_width"):
        scalar[key] = int(re.search(r"tf->%s = (\d+);" % key, text).group(1))
    scalar["reversed_border"] = re.search(r"tf->reversed_border = (\w+);", text).group(1) == "true"
    scalar["name"] = re.search(r'tf->name = strdup\("([^"]+)"\)', text).group(1)
    nbits = scalar["nbits"]
    bit_x = [None] * nbits
    bit_y = [None] * nbits
    for m in re.finditer(r"tf->bit_([xy])\[(\d+)\] = (-?\d+);", text):
        # upstream stores into uint32_t, so a negative cell wraps
        (bit_x if m.group(1) == "x" else bit_y)[int(m.group(2))] = int(m.group(3)) & 0xFFFFFFFF
    if len(codes) != scalar["ncodes"] or None in bit_x or None in bit_y or scalar["name"] != name:
        raise SystemExit("unexpected layout in " + name)
    return codes, bit_x, bit_y, scalar


def emit(name, text, src_name, out_dir):
    codes, bit_x, bit_y, s = parse(text, name)
    notice = text[text.index("/*"):text.index("*/") + 2]
    lines = [notice, "",
             "// Generated by tools/gen_families.py from AprilRobotics apriltag %s (%s); do not edit." % (UPSTREAM_TAG, src_name),
             '#include "FamilyTables.h"', "", "#include <cstdint>", "", "namespace apriltag_vulkan {", "", "namespace {", "",
             "const uint64_t kCodes[%d] = {" % len(codes)]
    for i in range(0, len(codes), 4):
        lines.append("    " + ", ".join("0x%016xULL" % c for c in codes[i:i + 4]) + ",")
    lines.append("};")
    lines.append("const uint32_t kBitX[%d] = {%s};" % (len(bit_x), ", ".join("%du" % v for v in bit_x)))
    lines.append("const uint32_t kBitY[%d] = {%s};" % (len(bit_y), ", ".join("%du" % v for v in bit_y)))
    lines += ["", "}  // namespace", "",
              "const Family %s = {\"%s\", %d, kCodes, %d, %d, %s, %d, kBitX, kBitY, %d};" % (
                  const_name(name), name, s["ncodes"], s["width_at_border"], s["total_width"],
                  "true" if s["reversed_border"] else "false", s["nbits"], s["h"]),
              "", "}  // namespace apriltag_vulkan", ""]
    (out_dir / (name + ".cpp")).write_text("\n".join(lines), encoding="utf-8", newline="\n")


def main():
    if len(sys.argv) < 2:
        raise SystemExit(__doc__)
    src = pathlib.Path(sys.argv[1])
    out = pathlib.Path(sys.argv[2]) if len(sys.argv) > 2 else pathlib.Path(__file__).resolve().parent.parent / "library" / "src" / "families"
    out.mkdir(parents=True, exist_ok=True)
    for name in FAMILIES:
        emit(name, (src / (name + ".c")).read_text(encoding="utf-8"), name + ".c", out)
    header = ["// Generated by tools/gen_families.py; do not edit.", "#pragma once", "",
              '#include "vkapriltag/Family.h"', "", "namespace apriltag_vulkan {", ""]
    header += ["extern const Family %s;" % const_name(n) for n in FAMILIES]
    header += ["", "}  // namespace apriltag_vulkan", ""]
    (out / "FamilyTables.h").write_text("\n".join(header), encoding="utf-8", newline="\n")
    print("wrote %d families to %s" % (len(FAMILIES), out))


if __name__ == "__main__":
    main()
