#pragma once

#include <cstddef>
#include <cstdint>

namespace apriltag_vulkan::vk {

// SPIR-V compiled into the binary at build time, so a deployed library needs
// nothing on disk beside it.
//
// The disk-based path (SHADER_DIR, see GpuDetector.cpp) predates this and is
// still the right thing for the sample app and the validation tools, which
// always run out of a build or install tree. It is the wrong thing for a
// library loaded from somewhere with no install prefix at all - most
// concretely, a JNI shared object extracted from a jar at runtime, which is
// how PhotonVision consumes its native dependencies. There is no directory to
// point SHADER_DIR at in that case, so the shaders have to travel inside the
// binary.
//
// Generated by cmake/GenerateEmbeddedShaders.cmake from the same .spv files
// the install rules ship. When VKAPRILTAG_EMBED_SHADERS=OFF the generator
// still runs, but emits an empty table and HasEmbeddedShaders() == false, so
// every caller falls back to loading from SHADER_DIR with no #ifdefs at the
// call site.
struct EmbeddedShader {
  const char *name;      // shader base name, e.g. "decimate"
  const uint32_t *code;  // SPIR-V words
  size_t bytes;          // byte count, always a multiple of 4
};

// The shader named `name` ("decimate", not "decimate.comp.spv"), or nullptr
// when embedding is disabled or the name is unknown.
const EmbeddedShader *FindEmbeddedShader(const char *name);

// True when this build has shaders compiled into it.
bool HasEmbeddedShaders();

// A digest of the embedded corpus, computed at build time over every
// shader's name and contents. vk::PipelineCache keys its on-disk file partly
// on this, so a shader rebuild lands on a fresh cache file rather than
// feeding stale entries back to the driver. 0 when embedding is disabled.
uint64_t EmbeddedShaderCorpusHash();

}  // namespace apriltag_vulkan::vk
